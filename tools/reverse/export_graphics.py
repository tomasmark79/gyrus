#!/usr/bin/env python3
"""Export data-only C++ graphics arrays from observed initialized game RAM.

No OS font or 6502 instructions are exported. The optional oracle mode runs
original drawing subroutines offline with py65 to independently check the port.
"""
import argparse
import hashlib
from pathlib import Path


def export(memory, destination):
    word = lambda address: memory[address] | memory[address + 1] << 8
    records, pixels, ids, known = [], [], [], {}
    for kind in range(29):
        metadata = word(0xac95 + 2 * kind)
        for depth in range(8):
            sizes = memory[metadata + 1 + depth // 2]
            height = (sizes >> (0 if depth & 1 else 4)) & 15
            stride = (height + 6) // 4
            for orientation in range(16):
                for alignment in range(2):
                    bank = word(0xaccf + 2 * kind + alignment * 0x3a)
                    source = word(bank + ((orientation >> 1) & 6))
                    source += memory[metadata + 5 + (orientation & 3)]
                    source += memory[metadata + 8 + height]
                    packed = bytes(memory[source:source + height * stride])
                    key = (height, stride, packed)
                    if key not in known:
                        known[key] = len(records)
                        records.append((len(pixels), stride, height))
                        pixels.extend(packed)
                    ids.append(known[key])
    # Four sizes, original and horizontally mirrored banks. Header offsets
    # select the five distinct rotations; subsequent bytes contain mask rows.
    ships, ship_offsets = [], []
    heights = (11, 6, 5, 3) * 2
    for index, height in enumerate(heights):
        source = word(0x9da3 + index * 2)
        # Smaller banks nominally contain two visible planes, but $9D31 still
        # fetches a third (usually at offscreen HPOS0). Preserve the entire
        # actually-read span, including neighboring data, rather than relying
        # on C++ array overreads to imitate adjacent original RAM.
        length = max(memory[source:source + 5]) + 3 * height
        ship_offsets.append(len(ships))
        ships.extend(memory[source:source + length])
    out = ['// Generated by tools/reverse/export_graphics.py. Data only; no CPU code.',
           '// Original ATR SHA-256 dd2ec0f5ca190c1f1446b76d67e1bd13e9a18e19d0792807b887474030752dcc.',
           f'// Initialized RAM SHA-256 {hashlib.sha256(memory).hexdigest()}.',
           '// Sprite variants include original startup-generated mirror/alignment data.',
           '// OS font deliberately excluded.', '#pragma once', '#include <array>',
           '#include <cstdint>', 'namespace gyrus::game::graphics_data {',
           'struct SpriteRecord { std::uint16_t offset; std::uint8_t stride, height; };']

    def array(name, kind, values):
        out.append(f'inline constexpr std::array<{kind}, {len(values)}> {name}{{{{')
        for start in range(0, len(values), 16):
            out.append('    ' + ', '.join(str(v) for v in values[start:start + 16]) + ',')
        out.append('}};')

    array('spriteRecords', 'SpriteRecord', ['{' + ','.join(map(str, r)) + '}' for r in records])
    array('spriteIds', 'std::uint16_t', ids)
    array('spriteBytes', 'std::uint8_t', pixels)
    array('titleBytes', 'std::uint8_t', memory[0xa909:0xa909 + 884])
    array('shipOffsets', 'std::uint16_t', ship_offsets)
    array('shipBytes', 'std::uint8_t', ships)
    out.append('} // namespace gyrus::game::graphics_data')
    destination.write_text('\n'.join(out) + '\n')
    print(f'Exported {len(records)} unique sprites, {len(pixels)} packed bytes, {len(ships)} ship bytes')


def fnv(values):
    result = 2166136261
    for value in values:
        result = ((result ^ value) * 16777619) & 0xffffffff
    return result


def oracle(memory):
    from py65.devices.mpu6502 import MPU

    def run(mem, entry):
        cpu = MPU(memory=mem, pc=entry)
        cpu.sp = 0xfd
        cpu.x = 1
        mem[0x1fe], mem[0x1ff] = 0xff, 0x6f
        for _ in range(100000):
            if cpu.pc == 0x7000:
                return cpu
            cpu.step()
        raise RuntimeError('Original drawing routine did not return')

    for kind, depth, orientation, x, y in [(3, 8, 0, 80, 48), (3, 8, 7, 81, 48),
                                         (3, 8, 13, 82, 48), (9, 24, 3, 83, 48),
                                         (12, 48, 9, 1, 1), (0, 40, 0, 80, 48),
                                         (3, 8, 0, 80, 0), (2, 8, 1, 80, 1)]:
        mem = list(memory)
        mem[0x30c4:0x3fc4] = [0] * 3840
        kindptr = mem[0xac95 + 2 * kind] | mem[0xac96 + 2 * kind] << 8
        sizes = mem[kindptr + 1 + depth // 16]
        size = (sizes >> (0 if depth & 8 else 4)) & 15
        mem[0x46f], mem[0x4c7] = x, y
        mem[0x5cf], mem[0x627], mem[0x67f] = size, orientation, 2 * kind
        cpu = run(mem, 0x9af8)
        pixels = [(v >> bit) & 3 for v in mem[0x30c4:0x3fc4] for bit in (6, 4, 2, 0)]
        print('sprite', kind, depth, orientation, x, y, 'hash', fnv(pixels), 'carry', cpu.p & 1)

    samples = [(0, 12), (16, 12), (32, 12), (48, 12), (64, 12),
                         (80, 12), (96, 12), (112, 12), (7, 20), (57, 28), (95, 40), (13, 58)]
    hashes = []
    for angle, depth in [(a, d) for d in (6,12,20,28,40,58) for a in range(128)]:
        mem = list(memory)
        mem[0x2200:0x2380] = [0] * 384
        mem[0xd000:0xd003] = [0, 0, 0]
        mem[0x51e], mem[0x576] = angle, depth
        run(mem, 0x9c14)
        pixels = [0] * 15360
        for plane in (2, 1, 0):
            xpos = mem[0xd000 + plane] - 48
            for row in range(96):
                # ANTIC begins its display list at physicalscanline8. After
                # 24 blank +8 HUD lines the bitmap begins at40, PM row20.
                # Live Atari800 collision probes confirmed $2238 maps to
                # bitmaprow36, not40; use $2214 as bitmaprow0.
                bits = mem[0x2214 + plane * 128 + row]
                for bit in range(8):
                    x = xpos + bit
                    if bits & (128 >> bit) and 0 <= x < 160:
                        pixels[row * 160 + x] = 4 + plane
        result = fnv(pixels)
        hashes.extend(result.to_bytes(4, 'little'))
        if (angle, depth) in samples:
            print('player', angle, depth, 'hash', result, 'hpos', mem[0xd000:0xd003])
    print('player 768-frame aggregate', fnv(hashes))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('memory', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/lib/Game/GraphicsData.hpp'))
    parser.add_argument('--oracle', action='store_true')
    args = parser.parse_args()
    memory = args.memory.read_bytes()
    if len(memory) != 65536:
        raise ValueError('Expected a complete 64KB initialized RAM dump')
    if args.oracle:
        oracle(memory)
    else:
        export(memory, args.output)
