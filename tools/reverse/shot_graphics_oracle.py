#!/usr/bin/env python3
"""Original $9A97 player-shot raster oracle, including projection and heading.

Requires offline py65. Writes only reference hashes for native session tests.
"""
from pathlib import Path
from py65.devices.mpu6502 import MPU


def run(memory, entry):
    cpu = MPU(memory=memory, pc=entry)
    cpu.sp, cpu.x = 0xfd, 1
    memory[0x1fe:0x200] = [0xff, 0x6f]
    for _ in range(100000):
        if cpu.pc == 0x7000:
            return cpu
        cpu.step()
    raise RuntimeError('Original routine did not return')


def raster_hash(memory):
    result = 2166136261
    for byte in memory[0x30c4:0x3fc4]:
        for shift in (6,4,2,0):
            result = ((result ^ ((byte >> shift) & 3)) * 16777619) & 0xffffffff
    return result


def main():
    original = list(Path('analysis/initialized-memory.bin').read_bytes())
    hashes, wrong_count = [], 0
    for angle in range(0,128,2):
        for depth in range(12,56,2):
            memory = original.copy()
            memory[0x30c4:0x3fc4] = [0] * 3840
            memory[0x51f], memory[0x577] = angle, depth
            memory[0x67f], memory[0x5cf], memory[0x627] = 0, 0, 15
            cpu = run(memory, 0x9a97)
            assert memory[0x627] == 0, (angle, depth)
            expected = raster_hash(memory)
            hashes.append(expected)
            memory[0x30c4:0x3fc4] = [0] * 3840
            memory[0x627] = angle // 8
            run(memory, 0x9af8)
            wrong_count += raster_hash(memory) != expected
    lines = ['// Generated by tools/reverse/shot_graphics_oracle.py from original $9A97.',
             '// Indexed by (angle/2)*22+(depth-12)/2. Angles0..126, depths12..54.',
             '#pragma once', '#include <array>', '#include <cstdint>',
             'namespace gyrus::test {',
             'inline constexpr std::array<std::uint32_t,1408> playerShotRasterHashes{{']
    for offset in range(0,len(hashes),8):
        lines.append('    ' + ','.join(str(v)+'u' for v in hashes[offset:offset+8]) + ',')
    lines += ['}};', f'inline constexpr unsigned wrongHeadingCases = {wrong_count};', '}']
    Path('tests/PlayerShotRasterData.hpp').write_text('\n'.join(lines)+'\n')
    print(f'1408 original rasters exported; angle/8 differs in {wrong_count} cases.')


if __name__ == '__main__':
    main()
